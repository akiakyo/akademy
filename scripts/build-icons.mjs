// Generates src/components/solar-icons.ts from the Solar set, Bold style only.
// Add a name to ICONS and run: node scripts/build-icons.mjs
import { readFileSync, writeFileSync } from "node:fs";

const set = JSON.parse(readFileSync(new URL("../node_modules/@iconify-json/solar/icons.json", import.meta.url)));

const ICONS = {
  home: "home-2",
  tutorials: "book",
  references: "library",
  exercises: "clipboard-list",
  editor: "programming",
  progress: "chart",
  search: "magnifier",
  example: "code-square",
  basics: "notebook",
  keywords: "key",
  tips: "lightbulb",
  deck: "layers",
  quiz: "clipboard-check",
  certificate: "diploma",
  medal: "medal-ribbon-star",
  cap: "square-academic-cap",
  run: "play",
  flip: "refresh",
  again: "restart",
  print: "printer",
  check: "check-circle",
  wrong: "close-circle",
  prev: "alt-arrow-left",
  next: "alt-arrow-right",
  back: "arrow-left",
  forward: "arrow-right",
  info: "info-circle",
  letter: "letter",
  shield: "shield-check",
  website: "global",
  code: "code-square",
  terms: "document-text",
};

const out = Object.entries(ICONS).map(([key, name]) => {
  const icon = set.icons[`${name}-bold`];
  if (!icon) throw new Error(`No Solar Bold icon named ${name}`);
  return `  ${key}: ${JSON.stringify(icon.body)},`;
});

writeFileSync(
  new URL("../src/components/solar-icons.ts", import.meta.url),
  `// Generated by scripts/build-icons.mjs. Solar icon set, Bold style.\nexport const SOLAR = {\n${out.join("\n")}\n} as const;\n\nexport type IconName = keyof typeof SOLAR;\n`,
);
console.log(`wrote ${out.length} icons`);
